import { test, expect, request as playwrightRequest } from "@playwright/test";

const API_BASE_URL = process.env.API_BASE_URL ?? "http://127.0.0.1:8000";
const uniqueSuffix = Date.now().toString();
const DOCTOR_EMAIL =
  process.env.TEST_DOCTOR_EMAIL ?? `doctor.ui.${uniqueSuffix}@example.com`;
const DOCTOR_PASSWORD =
  process.env.TEST_DOCTOR_PASSWORD ?? `Doctor!${uniqueSuffix}aA1`;
const RECEPTIONIST_EMAIL =
  process.env.TEST_RECEPTIONIST_EMAIL ??
  `reception.ui.${uniqueSuffix}@example.com`;
const RECEPTIONIST_PASSWORD =
  process.env.TEST_RECEPTIONIST_PASSWORD ??
  `Reception!${uniqueSuffix}aA1`;

let doctorAuth: { token: string; user: { _id: string } } | null = null;
let receptionistAuth: { token: string; user: { _id: string } } | null = null;
let queueEntryId: string | null = null;
let patientRecord: { _id: string; patientId?: string; fullName?: string } | null = null;

async function ensureUser(
  api: typeof playwrightRequest,
  email: string,
  password: string,
  role: "doctor" | "receptionist",
  extra: Record<string, unknown>
) {
  const loginResponse = await api.post(`${API_BASE_URL}/api/auth/login`, {
    data: { email, password },
  });

  if (loginResponse.ok()) {
    const payload = await loginResponse.json();
    return {
      token: payload.data.accessToken,
      user: payload.data.user,
    };
  }

  if (loginResponse.status() !== 401) {
    throw new Error(
      `Unexpected login failure (${loginResponse.status()}): ${await loginResponse.text()}`
    );
  }

  const registerPayload = {
    firstName: role === "doctor" ? "Dr UI" : "Reception",
    lastName: role === "doctor" ? "Automation" : "Assistant",
    email,
    password,
    role,
    phone: "+1-555-01" + uniqueSuffix.slice(-4),
    ...extra,
  };

  const registerResponse = await api.post(`${API_BASE_URL}/api/auth/register`, {
    data: registerPayload,
  });

  if (!registerResponse.ok()) {
    throw new Error(
      `Failed to register ${role}: (${registerResponse.status()}) ${await registerResponse.text()}`
    );
  }

  const payload = await registerResponse.json();
  return {
    token: payload.data.accessToken,
    user: payload.data.user,
  };
}

test.beforeAll(async ({ request }) => {
  doctorAuth = await ensureUser(request, DOCTOR_EMAIL, DOCTOR_PASSWORD, "doctor", {
    speciality: "General Physician",
    licenseNumber: `LIC-${uniqueSuffix}`,
    experience: 6,
  });

  receptionistAuth = await ensureUser(
    request,
    RECEPTIONIST_EMAIL,
    RECEPTIONIST_PASSWORD,
    "receptionist",
    {}
  );

  if (!doctorAuth || !receptionistAuth) {
    throw new Error("Failed to prepare authentication for test users.");
  }

  const patientEmail = `patient.ui.${uniqueSuffix}@example.com`;
  const patientResponse = await request.post(`${API_BASE_URL}/api/patients`, {
    headers: {
      Authorization: `Bearer ${doctorAuth.token}`,
    },
    data: {
      firstName: "UI",
      lastName: "Patient",
      gender: "Male",
      age: "35",
      bloodGroup: "O+",
      dateOfBirth: "1990-01-01",
      email: patientEmail,
      phone: "+1-555-0201",
      address: "123 Automation Ave, Test City",
      medicalHistory: "None",
      allergies: "None",
      emergencyContact: "UI Relative",
      emergencyContactPhone: "+1-555-0202",
    },
  });

  if (!patientResponse.ok()) {
    throw new Error(
      `Failed to create patient: (${patientResponse.status()}) ${await patientResponse.text()}`
    );
  }

  const patientPayload = await patientResponse.json();
  const patient = patientPayload.data.patient;
  patientRecord = patient;

  const now = new Date();
  const dateStr = now.toISOString().split("T")[0];
  const appointmentTime = new Date(now.getTime() + 5 * 60 * 1000)
    .toISOString()
    .substring(11, 16);

  const appointmentResponse = await request.post(
    `${API_BASE_URL}/api/appointments`,
    {
      headers: {
        Authorization: `Bearer ${receptionistAuth.token}`,
      },
      data: {
        patientId: patient._id,
        doctorId: doctorAuth.user._id,
        date: dateStr,
        time: appointmentTime,
        duration: 30,
        priority: "medium",
        reason: "UI Automation Consultation",
        notes: "Autogenerated appointment for UI test",
      },
    }
  );

  if (!appointmentResponse.ok()) {
    throw new Error(
      `Failed to create appointment: (${appointmentResponse.status()}) ${await appointmentResponse.text()}`
    );
  }

  const appointmentPayload = await appointmentResponse.json();
  const appointmentId = appointmentPayload.data.appointment._id;

  const checkInResponse = await request.post(
    `${API_BASE_URL}/api/queue/check-in`,
    {
      headers: {
        Authorization: `Bearer ${receptionistAuth.token}`,
      },
      data: {
        appointmentId,
        reason: "UI automation check-in",
        priority: "high",
        notes: "Automated test queue entry",
      },
    }
  );

  if (!checkInResponse.ok()) {
    throw new Error(
      `Failed to check in appointment: (${checkInResponse.status()}) ${await checkInResponse.text()}`
    );
  }

  const queuePayload = await checkInResponse.json();
  queueEntryId = queuePayload.data?._id ?? queuePayload.data?.queueEntry?._id ?? queuePayload.data?.queueEntry?.id ?? null;
  if (!queueEntryId) {
    console.warn("Queue check-in payload missing entry id:", queuePayload);
    queueEntryId =
      queuePayload.data?.id ??
      queuePayload.data?.queue?._id ??
      queuePayload.data?.queue?.id ??
      null;
  }
});

test("doctor can open consultation session from patient queue", async ({ page }) => {
  page.on("console", (msg) => {
    console.log("[browser]", msg.type(), msg.text());
  });
  page.on("response", (response) => {
    if (response.status() >= 400) {
      console.log("[response]", response.status(), response.url());
    }
  });
  page.on("pageerror", (error) => {
    console.log("[pageerror]", error.name, error.message);
  });
  // Login as doctor
  await page.goto("/auth?role=doctor");
  await page.getByLabel("Email").fill(DOCTOR_EMAIL);
  await page.getByLabel("Password").fill(DOCTOR_PASSWORD);
  await page.getByRole("button", { name: "Sign In" }).click();

  await page.waitForURL("**/doctor-dashboard", { timeout: 20_000 });
  await expect(page.getByText("Patient Queue", { exact: false })).toBeVisible();

  const queueCard = page
    .locator("div")
    .filter({
      hasText: patientRecord ? patientRecord.fullName ?? "UI Patient" : "UI Patient",
    })
    .last();

  const startButtonLocator = queueCard.locator('button:has-text("Start")');
  if (await startButtonLocator.count()) {
    await startButtonLocator.first().click();
    await page.waitForURL("**/consultation/**", { timeout: 20_000 });
  } else if (patientRecord && queueEntryId) {
    const targetPatientId = patientRecord.patientId ?? patientRecord._id;
    await page.goto(`/consultation/${targetPatientId}?queueId=${queueEntryId}`);
    await page.waitForURL("**/consultation/**", { timeout: 20_000 });
  } else {
    throw new Error(
      "Start button not found and queue entry details unavailable for direct navigation."
    );
  }

  const workspaceLoader = page.getByText("Loading your workspace…", {
    exact: false,
  });
  if (await workspaceLoader.count()) {
    await workspaceLoader.first().waitFor({ state: "hidden", timeout: 20_000 }).catch(() => undefined);
  }

  const sessionLoader = page.getByText("Loading Consultation Session", {
    exact: false,
  });
  if (await sessionLoader.count()) {
    await sessionLoader.first().waitFor({ state: "hidden", timeout: 20_000 }).catch(() => undefined);
  }

  const stopRecordingButton = page.getByRole("button", { name: "Stop Recording" });
  await expect(stopRecordingButton).toBeVisible({ timeout: 15_000 });
  await stopRecordingButton.click();

  const pageSnapshot = await page.locator("body").innerText();
  console.log("Consultation page snapshot:", pageSnapshot.slice(0, 500));
  await expect(
    page.getByText("Transcription Complete", {
      exact: false,
    })
  ).toBeVisible({ timeout: 20_000 });
  await expect(page.getByRole("button", { name: "End Consultation" })).toBeVisible();
});

